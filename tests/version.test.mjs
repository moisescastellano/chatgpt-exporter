import assert from "node:assert/strict";
import { createRequire } from "node:module";
import { test } from "node:test";

import { APP_VERSION, conversationToMarkdown } from "../lib/markdown.js";

const require = createRequire(import.meta.url);
const packageJson = require("../package.json");

test("application version comes from package.json", () => {
  assert.equal(APP_VERSION, packageJson.version);
  assert.match(APP_VERSION, /^\d+\.\d+\.\d+(?:[-+].+)?$/);
});

test("Markdown footer includes the application version", () => {
  const convo = {
    title: "Version test",
    mapping: {
      root: { parent: null, children: ["user"], message: null },
      user: {
        parent: "root",
        children: ["assistant"],
        message: {
          author: { role: "user" },
          content: { content_type: "text", parts: ["Hello"] },
          metadata: {},
        },
      },
      assistant: {
        parent: "user",
        children: [],
        message: {
          author: { role: "assistant" },
          content: { content_type: "text", parts: ["Hi"] },
          metadata: {},
          channel: "final",
        },
      },
    },
    current_node: "assistant",
  };

  const md = conversationToMarkdown(convo);
  assert.ok(md.includes(`Generated by [ChatGPT Exporter](https://github.com/moisescastellano/chatgpt-exporter) v${APP_VERSION}`));
});
