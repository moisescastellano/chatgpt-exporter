import assert from "node:assert/strict";
import { test } from "node:test";

import { APP_VERSION, conversationToMarkdown } from "../lib/markdown.js";

const FOOTER = `*Generated by [ChatGPT Exporter](https://github.com/moisescastellano/chatgpt-exporter) v${APP_VERSION}*`;

function conversation() {
  return {
    title: "Footer test",
    mapping: {
      root: { parent: null, children: ["user"], message: null },
      user: {
        parent: "root",
        children: ["assistant"],
        message: {
          author: { role: "user" },
          content: { content_type: "text", parts: ["Hello"] },
          metadata: {},
        },
      },
      assistant: {
        parent: "user",
        children: [],
        message: {
          author: { role: "assistant" },
          content: { content_type: "text", parts: ["Hi"] },
          metadata: {},
          channel: "final",
        },
      },
    },
    current_node: "assistant",
  };
}

test("Markdown ends with the ChatGPT Exporter footer", () => {
  const md = conversationToMarkdown(conversation());
  assert.ok(md.endsWith(`---\n\n${FOOTER}`));
});

test("Generated by footer is emitted exactly once", () => {
  const md = conversationToMarkdown(conversation());
  assert.equal(md.split(FOOTER).length - 1, 1);
});
